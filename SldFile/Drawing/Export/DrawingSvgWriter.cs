using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security;
using System.Text;
using SldFile.Drawing.Vector;

namespace SldFile.Drawing.Export;

/// <summary>
/// Generates standard W3C SVG vector graphic exchange files from 2D CAD drawing sheets.
/// Exports true lossless mathematical vector CAD geometry, dimensions, and typography.
/// </summary>
public static class DrawingSvgWriter
{
    /// <summary>
    /// Writes the drawing sheet vector data as an SVG XML string.
    /// </summary>
    public static string Write(DrawingSheetVectorData vectorData, string sheetName = "Sheet1")
    {
        var sb = new StringBuilder();
        using var writer = new StringWriter(sb, CultureInfo.InvariantCulture);
        Write(vectorData, writer, sheetName);
        return sb.ToString();
    }

    /// <summary>
    /// Writes the drawing sheet vector data to the specified TextWriter in W3C SVG format.
    /// </summary>
    public static void Write(DrawingSheetVectorData vectorData, TextWriter writer, string sheetName = "Sheet1")
    {
        if (vectorData == null) throw new ArgumentNullException(nameof(vectorData));
        if (writer == null) throw new ArgumentNullException(nameof(writer));

        double widthMm = vectorData.PaperWidthMm > 10.0 ? vectorData.PaperWidthMm : 297.0;
        double heightMm = vectorData.PaperHeightMm > 10.0 ? vectorData.PaperHeightMm : 210.0;

        writer.WriteLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>");
        writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
            "<svg xmlns=\"http://www.w3.org/2000/svg\" version=\"1.1\" width=\"{0:F1}mm\" height=\"{1:F1}mm\" viewBox=\"0 0 {2:F3} {3:F3}\">",
            widthMm, heightMm, widthMm, heightMm));

        // SVG Metadata & Title
        writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
            "  <title>{0}</title>", SecurityElement.Escape(sheetName ?? "Sheet")));
        writer.WriteLine("  <desc>Generated by SldFile - SolidWorks Drawing Pure Vector CAD Engine</desc>");

        // Styles & Definitions
        writer.WriteLine("  <defs>");
        writer.WriteLine("    <style>");
        writer.WriteLine("      .sheet-border-outer { stroke: #000000; stroke-width: 0.50; fill: none; }");
        writer.WriteLine("      .sheet-border-inner { stroke: #000000; stroke-width: 0.70; fill: none; }");
        writer.WriteLine("      .table-grid { stroke: #000000; stroke-width: 0.25; fill: none; }");
        writer.WriteLine("      .solid-outline { stroke: #000000; stroke-width: 0.50; fill: none; stroke-linecap: round; stroke-linejoin: round; }");
        writer.WriteLine("      .thin-line { stroke: #000000; stroke-width: 0.25; fill: none; stroke-linecap: round; stroke-linejoin: round; }");
        writer.WriteLine("      .centerline { stroke: #D32F2F; stroke-width: 0.25; stroke-dasharray: 10,2,2,2; fill: none; }");
        writer.WriteLine("      .hidden-line { stroke: #616161; stroke-width: 0.25; stroke-dasharray: 3,2; fill: none; }");
        writer.WriteLine("      .dimension-line { stroke: #0055A5; stroke-width: 0.25; fill: none; }");
        writer.WriteLine("      .cad-text { font-family: 'Century Gothic', 'SimSun', 'Microsoft YaHei', Arial, sans-serif; fill: #000000; }");
        writer.WriteLine("      .dim-text { font-family: 'Century Gothic', 'SimSun', Arial, sans-serif; fill: #0055A5; }");
        writer.WriteLine("    </style>");

        // Standard Dimension Arrowhead Marker
        writer.WriteLine("    <marker id=\"dim-arrow\" viewBox=\"0 0 10 10\" refX=\"10\" refY=\"5\" markerWidth=\"4\" markerHeight=\"4\" orient=\"auto-start-reverse\">");
        writer.WriteLine("      <path d=\"M 0 2 L 10 5 L 0 8 z\" fill=\"#0055A5\" />");
        writer.WriteLine("    </marker>");
        writer.WriteLine("    <marker id=\"view-arrow\" viewBox=\"0 0 10 10\" refX=\"10\" refY=\"5\" markerWidth=\"5\" markerHeight=\"5\" orient=\"auto-start-reverse\">");
        writer.WriteLine("      <path d=\"M 0 1.5 L 10 5 L 0 8.5 z\" fill=\"#000000\" />");
        writer.WriteLine("    </marker>");
        writer.WriteLine("  </defs>");

        // Paper Background
        writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
            "  <rect id=\"paper-background\" x=\"0\" y=\"0\" width=\"{0:F3}\" height=\"{1:F3}\" fill=\"#FFFFFF\" />",
            widthMm, heightMm));

        // Coordinate transformation:
        // CAD coordinate system has (0, 0) at lower-left, Y pointing UP.
        // SVG coordinate system has (0, 0) at upper-left, Y pointing DOWN.
        // Therefore: svgX = cadX, svgY = heightMm - cadY.
        double ToSvgY(double cadY) => heightMm - cadY;

        // 1. Group: Sheet Borders and Title Block Grids
        var borderLines = vectorData.Lines.Where(l =>
            l.Kind == DrawingLineKind.SheetBorderOuter ||
            l.Kind == DrawingLineKind.SheetBorderInner ||
            l.Kind == DrawingLineKind.TableGrid).ToList();

        if (borderLines.Count > 0)
        {
            writer.WriteLine("  <g id=\"sheet-borders-and-tables\">");
            foreach (var line in borderLines)
            {
                string cls = line.Kind switch
                {
                    DrawingLineKind.SheetBorderOuter => "sheet-border-outer",
                    DrawingLineKind.SheetBorderInner => "sheet-border-inner",
                    _ => "table-grid"
                };

                writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
                    "    <line x1=\"{0:F3}\" y1=\"{1:F3}\" x2=\"{2:F3}\" y2=\"{3:F3}\" class=\"{4}\" />",
                    line.X1, ToSvgY(line.Y1), line.X2, ToSvgY(line.Y2), cls));
            }
            writer.WriteLine("  </g>");
        }

        // 2. Group: Model Geometry Lines (Outlines, Features, Centerlines, Hidden)
        var modelLines = vectorData.Lines.Where(l =>
            l.Kind == DrawingLineKind.SolidOutline ||
            l.Kind == DrawingLineKind.ThinLine ||
            l.Kind == DrawingLineKind.Centerline ||
            l.Kind == DrawingLineKind.HiddenLine).ToList();

        if (modelLines.Count > 0)
        {
            writer.WriteLine("  <g id=\"model-geometry\">");
            foreach (var line in modelLines)
            {
                string cls = line.Kind switch
                {
                    DrawingLineKind.SolidOutline => "solid-outline",
                    DrawingLineKind.Centerline => "centerline",
                    DrawingLineKind.HiddenLine => "hidden-line",
                    _ => "thin-line"
                };

                writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
                    "    <line x1=\"{0:F3}\" y1=\"{1:F3}\" x2=\"{2:F3}\" y2=\"{3:F3}\" class=\"{4}\" />",
                    line.X1, ToSvgY(line.Y1), line.X2, ToSvgY(line.Y2), cls));
            }
            writer.WriteLine("  </g>");
        }

        // 3. Group: Dimension Lines
        var dimLines = vectorData.Lines.Where(l => l.Kind == DrawingLineKind.DimensionLine).ToList();
        if (dimLines.Count > 0)
        {
            writer.WriteLine("  <g id=\"dimension-geometry\">");
            foreach (var line in dimLines)
            {
                writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
                    "    <line x1=\"{0:F3}\" y1=\"{1:F3}\" x2=\"{2:F3}\" y2=\"{3:F3}\" class=\"dimension-line\" />",
                    line.X1, ToSvgY(line.Y1), line.X2, ToSvgY(line.Y2)));
            }
            writer.WriteLine("  </g>");
        }

        // 4. Group: Typography and Annotations (Title block, dimensions, notes)
        if (vectorData.Texts != null && vectorData.Texts.Count > 0)
        {
            writer.WriteLine("  <g id=\"annotations-and-typography\">");
            foreach (var text in vectorData.Texts)
            {
                if (string.IsNullOrWhiteSpace(text.CleanText)) continue;
                if (text.Category == DrawingVectorTextCategory.Metadata) continue;

                double x = text.X;
                double y = ToSvgY(text.Y);
                double fontSize = text.HeightMm > 0.5 ? text.HeightMm : 2.5;

                string cls = (text.Category == DrawingVectorTextCategory.ViewAnnotation) ? "dim-text" : "cad-text";
                string escapedContent = SecurityElement.Escape(text.CleanText);

                if (Math.Abs(text.AngleRad) > 1e-4)
                {
                    // SolidWorks counter-clockwise radians to SVG clockwise degrees
                    double deg = -text.AngleRad * (180.0 / Math.PI);
                    writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
                        "    <text x=\"{0:F3}\" y=\"{1:F3}\" font-size=\"{2:F2}\" class=\"{3}\" transform=\"rotate({4:F1}, {0:F3}, {1:F3})\">{5}</text>",
                        x, y, fontSize, cls, deg, escapedContent));
                }
                else
                {
                    writer.WriteLine(string.Format(CultureInfo.InvariantCulture,
                        "    <text x=\"{0:F3}\" y=\"{1:F3}\" font-size=\"{2:F2}\" class=\"{3}\">{4}</text>",
                        x, y, fontSize, cls, escapedContent));
                }
            }
            writer.WriteLine("  </g>");
        }

        writer.WriteLine("</svg>");
    }
}
